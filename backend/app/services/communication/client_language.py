    ("AI-powered", "technology-enabled"),
    ("AI automation and cloud operations", "workflow automation and cloud operations"),
    ("AI automation", "workflow automation"),
    ("cloud/AI operations", "cloud and workflow operations"),
    ("JARVIS", "Aliyar Solutions"),
    ("Jarvis", "Aliyar Solutions"),
    ("jarvis", "Aliyar Solutions"),
    ("AI-generated", "consulting-prepared"),
    ("AI generated", "consulting-prepared"),
    ("machine-generated proposal", "consulting proposal"),
    ("AI agent", "operations specialist"),
    ("AI agents", "operations specialists"),
    ("autonomous system", "managed operating process"),
