BLOCKED_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"\bAI\s+orchestration\b", re.I), "operational coordination"),
    (re.compile(r"\bAI\s+tool(?:s)?\b", re.I), "workflow systems"),
    (re.compile(r"\bchatbot\b", re.I), "support workflow"),
    (re.compile(r"\bbot\b", re.I), "workflow assistant"),
)


def sanitize_client_text(value: Optional[str]) -> str:
    """Remove internal system language from client-visible copy."""
    if not value:
        return ""
    text = str(value)
    for old, new in BLOCKED_REPLACEMENTS:
        text = text.replace(old, new)
    for pattern, replacement in BLOCKED_PATTERNS:
        text = pattern.sub(replacement, text)
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def sanitize_subject_body(subject: Optional[str], body: Optional[str]) -> tuple[str, str]:
    return sanitize_client_text(subject), sanitize_client_text(body)
