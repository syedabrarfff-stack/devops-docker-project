    ("Qualified by JARVIS", "Qualified through operational review"),
    ("Generated by JARVIS", "Prepared by Aliyar Solutions"),
    ("Reviewed by JARVIS", "Reviewed by our operations team"),
    ("JARVIS identified", "Our consulting team identified"),
    ("JARVIS recommends", "Our operations team recommends"),
    ("JARVIS prepared", "Our operations team prepared"),
